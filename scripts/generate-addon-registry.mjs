import { createHash, createPublicKey, verify } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { isAbsolute, relative, resolve, sep } from "node:path";

const root = process.cwd();
const buildInputs = await readBuildInputs();
const configPath = resolveBuildPath(
  buildInputs.registryFile,
  "addons.registry.json",
);
const releasePublicKeysPath = resolveBuildPath(
  buildInputs.releasePublicKeysFile,
  "addon-release-public-keys.json",
);
const outputPath = resolve(root, ".generated", "addon-registry.ts");
const allowlist = new Map([
  ["webshop", "@radomirradojevic/webshop/server"],
  ["license-server", "@radomirradojevic/license-server-addon/server"],
]);
const expectedHostBindings = {
  "license-server": [
    "customerLicenseIssuer.jobs.v1",
    "customerLicenseIssuer.v1",
    "customerLicenseIssuer.v2",
    "routes.licenseServer",
  ],
  webshop: [
    "webshop.api.v1",
    "webshop.dashboard.v1",
    "webshop.download.v1",
    "webshop.file-authorization.v1",
    "webshop.form-submission-visibility.v1",
    "webshop.fulfillment-job.v1",
    "webshop.license-delivery.v1",
    "webshop.paddle-webhook.v1",
    "webshop.post-issue-delivery-job.v1",
    "webshop.purchase-intent-accept.v1",
    "webshop.storefront.v1",
  ],
};
const sourceMode = process.env.NR_ADDON_SOURCE_MODE?.trim();
if (
  sourceMode &&
  !["private_workspace", "registry", "empty"].includes(sourceMode)
) {
  throw new Error(
    "NR_ADDON_SOURCE_MODE is invalid for add-on registry generation.",
  );
}
const raw =
  sourceMode === "empty"
    ? { addons: [] }
    : JSON.parse(await readFile(configPath, "utf8"));
const addons = Array.isArray(raw?.addons) ? raw.addons : [];
const releasePublicKeys =
  addons.length > 0 ? await readReleasePublicKeys() : {};
const entries = [];
for (const item of addons) {
  if (
    !item ||
    typeof item !== "object" ||
    typeof item.addonKey !== "string" ||
    typeof item.packageName !== "string"
  )
    throw new Error("Invalid addon registry entry.");
  const specifier = allowlist.get(item.addonKey);
  if (!specifier || item.packageName !== specifier.replace(/\/server$/, ""))
    throw new Error(`Unallowlisted addon registry entry: ${item.addonKey}`);
  await verifyInstalledRelease(item, releasePublicKeys);
  entries.push(
    `  ${JSON.stringify(item.addonKey)}: () => import(${JSON.stringify(specifier)}),`,
  );
}
const output = `/* Generated by scripts/generate-addon-registry.mjs. Do not edit manually. */\nexport const addonLoaders = {\n${entries.join("\n")}\n} as const;\n\nexport type RegisteredAddonKey = keyof typeof addonLoaders;\nexport type AddonLoader = () => Promise<unknown>;\n\nexport function getAddonLoader(addonKey: string): AddonLoader | null {\n  return (addonLoaders[addonKey as RegisteredAddonKey] as AddonLoader | undefined) ?? null;\n}\n`;
await mkdir(resolve(root, ".generated"), { recursive: true });
await writeFile(outputPath, output, "utf8");

async function readReleasePublicKeys() {
  let parsed;
  try {
    parsed = JSON.parse(await readFile(releasePublicKeysPath, "utf8"));
  } catch {
    throw new Error(
      "The add-on release public-key file is missing or invalid.",
    );
  }
  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed))
    throw new Error("Addon release public key set must be an object.");
  const entries =
    parsed.contractVersion === 1 && Array.isArray(parsed.keys)
      ? parsed.keys
          .filter((entry) => entry?.status !== "revoked")
          .map((entry) => [entry?.kid, entry?.publicKeyPem])
      : Object.entries(parsed);
  const keys = new Map();
  for (const [kid, pem] of entries) {
    if (
      !/^[A-Za-z0-9._:-]{3,200}$/.test(kid) ||
      typeof pem !== "string" ||
      !pem.includes("BEGIN PUBLIC KEY")
    )
      throw new Error(
        "Addon release public key set contains an invalid entry.",
      );
    let key;
    try {
      key = createPublicKey(pem);
    } catch {
      throw new Error(
        "Addon release public key set contains an unreadable key.",
      );
    }
    if (key.asymmetricKeyType !== "ed25519")
      throw new Error(
        "Addon release authority keys must be Ed25519 public keys.",
      );
    keys.set(kid, pem);
  }
  if (keys.size === 0)
    throw new Error("Addon release public key set is empty.");
  return keys;
}

async function readBuildInputs() {
  const path = resolve(root, ".tmp", "addon-build-inputs.json");
  if (!existsSync(path)) return {};
  let parsed;
  try {
    parsed = JSON.parse(await readFile(path, "utf8"));
  } catch {
    throw new Error("Local add-on build inputs are invalid.");
  }
  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
    throw new Error("Local add-on build inputs must be an object.");
  }
  return parsed;
}

function resolveBuildPath(value, fallback) {
  const path = resolve(
    root,
    typeof value === "string" && value ? value : fallback,
  );
  if (!isWithin(root, path)) {
    throw new Error(
      "Add-on build input paths must stay inside the CMS workspace.",
    );
  }
  return path;
}

async function verifyInstalledRelease(expected, publicKeys) {
  if (
    typeof expected.packageVersion !== "string" ||
    !/^[a-f0-9]{64}$/.test(expected.artifactSha256 ?? "") ||
    typeof expected.signingKid !== "string" ||
    !/^[a-f0-9]{64}$/.test(expected.embeddedManifestSha256 ?? "")
  ) {
    throw new Error(
      `Registry entry ${expected.addonKey} must pin packageVersion, artifactSha256 and signingKid.`,
    );
  }
  const packageRoot = resolve(
    root,
    "node_modules",
    ...expected.packageName.split("/"),
  );
  const [packageJson, manifestBytes] = await Promise.all([
    readJson(
      resolve(packageRoot, "package.json"),
      `${expected.addonKey} package metadata`,
    ),
    readFile(resolve(packageRoot, "release-manifest.json")),
  ]);
  let manifest;
  try {
    manifest = JSON.parse(manifestBytes.toString("utf8"));
  } catch {
    throw new Error(
      `${expected.addonKey} release manifest is missing or invalid.`,
    );
  }
  if (
    manifest &&
    typeof manifest === "object" &&
    "protected" in manifest &&
    "payload" in manifest &&
    "signature" in manifest
  ) {
    await verifyInstalledReleaseV2({
      expected,
      publicKeys,
      packageRoot,
      packageJson,
      manifest,
      manifestBytes,
    });
    return;
  }
  const provenance = await readJson(
    resolve(packageRoot, "provenance.json"),
    `${expected.addonKey} provenance`,
  );
  if (
    packageJson.name !== expected.packageName ||
    packageJson.version !== expected.packageVersion ||
    manifest.manifestVersion !== 1 ||
    manifest.runtimeContractVersion !== "1" ||
    manifest.addonKey !== expected.addonKey ||
    manifest.packageName !== expected.packageName ||
    manifest.packageVersion !== expected.packageVersion ||
    manifest.artifact?.sha256 !== expected.artifactSha256 ||
    provenance.subject?.sha256 !== expected.artifactSha256 ||
    manifest.signingKid !== expected.signingKid
  ) {
    throw new Error(
      `Installed addon release identity mismatch: ${expected.addonKey}.`,
    );
  }
  const requiredBindings = expectedHostBindings[expected.addonKey];
  if (requiredBindings) {
    const actualBindings = manifest.hostRouteBindings;
    if (
      !Array.isArray(actualBindings) ||
      actualBindings.length !== requiredBindings.length ||
      new Set(actualBindings).size !== actualBindings.length ||
      requiredBindings.some((binding) => !actualBindings.includes(binding))
    ) {
      throw new Error(
        `Installed addon host bindings mismatch: ${expected.addonKey}.`,
      );
    }
  }
  if (
    !Array.isArray(manifest.artifact?.files) ||
    manifest.artifact.files.length === 0
  )
    throw new Error(
      `Installed addon release has no artifact inventory: ${expected.addonKey}.`,
    );
  const aggregateInput = stablePretty(manifest.artifact.files);
  const aggregateSha256 = sha256(Buffer.from(aggregateInput, "utf8"));
  if (
    aggregateSha256 !== manifest.artifact.sha256 ||
    Buffer.byteLength(aggregateInput) !== manifest.artifact.size ||
    (manifest.artifact.registryIntegrity &&
      manifest.artifact.registryIntegrity !==
        `sha256-${Buffer.from(aggregateSha256, "hex").toString("base64")}`)
  ) {
    throw new Error(
      `Installed addon release aggregate checksum mismatch: ${expected.addonKey}.`,
    );
  }
  if (
    typeof manifest.signature !== "string" ||
    !/^[A-Za-z0-9_-]{86}$/.test(manifest.signature)
  )
    throw new Error(
      `Installed addon release signature is malformed: ${expected.addonKey}.`,
    );
  const publicKey = publicKeys.get(manifest.signingKid);
  if (!publicKey)
    throw new Error(
      `Installed addon release uses an unpinned signing key: ${expected.addonKey}.`,
    );
  const { signature, ...unsigned } = manifest;
  if (
    !verify(
      null,
      Buffer.from(canonicalJson(unsigned), "utf8"),
      publicKey,
      Buffer.from(signature, "base64url"),
    )
  )
    throw new Error(
      `Installed addon release signature verification failed: ${expected.addonKey}.`,
    );

  const inventoryPaths = new Set();
  for (const file of manifest.artifact.files) {
    if (
      !file ||
      typeof file.path !== "string" ||
      !/^[A-Za-z0-9._/-]+$/.test(file.path) ||
      typeof file.sha256 !== "string" ||
      !/^[a-f0-9]{64}$/.test(file.sha256) ||
      !Number.isSafeInteger(file.size) ||
      file.size < 0
    )
      throw new Error(
        `Installed addon release inventory is invalid: ${expected.addonKey}.`,
      );
    if (inventoryPaths.has(file.path))
      throw new Error(
        `Installed addon release inventory contains duplicate paths: ${expected.addonKey}.`,
      );
    const artifactPath = resolve(packageRoot, file.path);
    if (!isWithin(packageRoot, artifactPath))
      throw new Error(
        `Installed addon release inventory escapes its package: ${expected.addonKey}.`,
      );
    let contents;
    try {
      contents = await readFile(artifactPath);
    } catch {
      throw new Error(
        `Installed addon release artifact is missing: ${expected.addonKey}.`,
      );
    }
    if (contents.byteLength !== file.size || sha256(contents) !== file.sha256)
      throw new Error(
        `Installed addon release artifact checksum mismatch: ${expected.addonKey}.`,
      );
    inventoryPaths.add(file.path.replace(/^\.\//, ""));
  }
  const serverEntrypoint = String(manifest.entrypoints?.server ?? "").replace(
    /^\.\//,
    "",
  );
  if (!inventoryPaths.has(serverEntrypoint))
    throw new Error(
      `Installed addon server entrypoint is outside the signed artifact inventory: ${expected.addonKey}.`,
    );
}

async function verifyInstalledReleaseV2({
  expected,
  publicKeys,
  packageRoot,
  packageJson,
  manifest,
  manifestBytes,
}) {
  if (Object.keys(manifest).sort().join(",") !== "payload,protected,signature")
    throw new Error("Installed V2 release envelope shape is invalid.");
  let header;
  let payload;
  try {
    header = JSON.parse(
      Buffer.from(manifest.protected, "base64url").toString("utf8"),
    );
    payload = JSON.parse(
      Buffer.from(manifest.payload, "base64url").toString("utf8"),
    );
  } catch {
    throw new Error("Installed V2 release envelope encoding is invalid.");
  }
  if (
    !header ||
    header.alg !== "EdDSA" ||
    header.typ !== "NRV-ADDON-RELEASE-MANIFEST-V2+JWS" ||
    header.kid !== expected.signingKid ||
    !/^[A-Za-z0-9][A-Za-z0-9._:-]{2,119}$/.test(header.kid) ||
    Object.keys(header).sort().join(",") !== "alg,kid,typ" ||
    !payload ||
    payload.manifestVersion !== 2 ||
    payload.purpose !== "addon_release_manifest" ||
    payload.addonKey !== expected.addonKey ||
    payload.packageName !== expected.packageName ||
    payload.packageVersion !== expected.packageVersion ||
    payload.runtimeContractVersion !== "1" ||
    payload.artifactSha256 !== expected.artifactSha256 ||
    payload.releaseSigningKid !== header.kid ||
    packageJson.name !== expected.packageName ||
    packageJson.version !== expected.packageVersion
  )
    throw new Error(
      `Installed V2 addon release identity mismatch: ${expected.addonKey}.`,
    );
  const publicKey = publicKeys.get(header.kid);
  if (
    !publicKey ||
    !verify(
      null,
      Buffer.from(`${manifest.protected}.${manifest.payload}`, "ascii"),
      publicKey,
      Buffer.from(manifest.signature, "base64url"),
    )
  )
    throw new Error(
      `Installed V2 addon release signature verification failed: ${expected.addonKey}.`,
    );
  const requiredBindings = expectedHostBindings[expected.addonKey];
  if (
    !Array.isArray(payload.capabilities) ||
    payload.capabilities.length !== requiredBindings.length ||
    new Set(payload.capabilities).size !== payload.capabilities.length ||
    requiredBindings.some((binding) => !payload.capabilities.includes(binding))
  )
    throw new Error(
      `Installed V2 addon host bindings mismatch: ${expected.addonKey}.`,
    );
  const entries = payload.artifactInventory?.entries;
  if (
    !Array.isArray(entries) ||
    entries.length === 0 ||
    !/^[a-f0-9]{64}$/.test(
      payload.artifactInventory?.entries?.[0]?.sha256 ?? "",
    )
  )
    throw new Error(
      `Installed V2 addon artifact inventory is invalid: ${expected.addonKey}.`,
    );
  const aggregate = sha256(
    Buffer.from(
      canonicalJson({
        contractVersion: 1,
        digestPurpose: "addon_runtime_payload",
        entries,
      }),
      "utf8",
    ),
  );
  if (
    aggregate !== expected.artifactSha256 ||
    payload.artifactSha256 !== aggregate ||
    sha256(manifestBytes) !==
      (expected.embeddedManifestSha256 ?? sha256(manifestBytes))
  )
    throw new Error(
      `Installed V2 addon artifact checksum mismatch: ${expected.addonKey}.`,
    );
  const paths = new Set();
  for (const file of entries) {
    if (
      !file ||
      typeof file.path !== "string" ||
      !/^[A-Za-z0-9._/-]+$/.test(file.path) ||
      file.path.includes("..") ||
      typeof file.sha256 !== "string" ||
      !/^[a-f0-9]{64}$/.test(file.sha256) ||
      !Number.isSafeInteger(file.size) ||
      file.size < 0 ||
      paths.has(file.path)
    )
      throw new Error(
        `Installed V2 addon inventory is invalid: ${expected.addonKey}.`,
      );
    const artifactPath = resolve(packageRoot, file.path);
    if (!isWithin(packageRoot, artifactPath))
      throw new Error(
        `Installed V2 addon artifact escapes package: ${expected.addonKey}.`,
      );
    let contents;
    try {
      contents = await readFile(artifactPath);
    } catch {
      throw new Error(
        `Installed V2 addon artifact is missing: ${expected.addonKey}.`,
      );
    }
    if (contents.byteLength !== file.size || sha256(contents) !== file.sha256)
      throw new Error(
        `Installed V2 addon artifact checksum mismatch: ${expected.addonKey}.`,
      );
    paths.add(file.path);
  }
  if (
    !paths.has(String(payload.entrypoints?.server ?? "").replace(/^\.\//, ""))
  )
    throw new Error(
      `Installed V2 addon server entrypoint is outside inventory: ${expected.addonKey}.`,
    );
}

async function readJson(path, label) {
  try {
    return JSON.parse(await readFile(path, "utf8"));
  } catch {
    throw new Error(`${label} is missing or invalid.`);
  }
}

function canonicalJson(value) {
  return JSON.stringify(sortValue(value));
}

function stablePretty(value) {
  return JSON.stringify(sortValue(value), null, 2);
}

function sortValue(value) {
  if (Array.isArray(value)) return value.map(sortValue);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(
    Object.entries(value)
      .filter(([, entry]) => entry !== undefined)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, entry]) => [key, sortValue(entry)]),
  );
}

function sha256(contents) {
  return createHash("sha256").update(contents).digest("hex");
}

function isWithin(parent, child) {
  const path = relative(parent, child);
  return (
    path !== "" &&
    path !== ".." &&
    !path.startsWith(`..${sep}`) &&
    !isAbsolute(path)
  );
}
